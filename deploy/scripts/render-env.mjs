#!/usr/bin/env node
/**
 * Render `deploy/app.env` (runtime) and refresh the infrastructure values in
 * `deploy/.env` (Compose interpolation) from the workstation's `.env`.
 *
 *   node deploy/scripts/render-env.mjs [https://tartly.in]
 *
 * Rules
 *  - Provider/API keys come from the repo-root `.env`.
 *  - Production topology (Postgres/Redis hostnames, public URLs) always wins.
 *  - Generated secrets are persisted: re-running never rotates a live secret.
 *  - Nothing secret is printed; only a summary of names and missing values.
 */

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const deployDir = resolve(here, "..");
const repoRoot = resolve(deployDir, "..");

const origin = (process.argv[2] ?? process.env.PUBLIC_URL ?? "https://tartly.in").replace(/\/$/, "");
const domain = new URL(origin).hostname;

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function readEnv(path) {
  return existsSync(path) ? parseEnv(readFileSync(path, "utf8")) : {};
}

/** Quote only when the value would otherwise be ambiguous to dotenv readers. */
function serialize(key, value) {
  const v = String(value ?? "");
  if (v === "" || /[\s#"']/.test(v)) {
    return `${key}="${v.replace(/"/g, '\\"')}"`;
  }
  return `${key}=${v}`;
}

const rootEnv = readEnv(resolve(repoRoot, ".env"));
const infra = readEnv(resolve(deployDir, ".env"));
const existingApp = readEnv(resolve(deployDir, "app.env"));

const isPlaceholder = (v) => !v || /^change[-_]?me/i.test(v);

const postgresPassword = !isPlaceholder(infra.POSTGRES_PASSWORD)
  ? infra.POSTGRES_PASSWORD
  : randomBytes(24).toString("hex");
const redisToken = !isPlaceholder(infra.REDIS_REST_TOKEN)
  ? infra.REDIS_REST_TOKEN
  : randomBytes(24).toString("hex");

const metricsToken =
  !isPlaceholder(existingApp.METRICS_TOKEN) && existingApp.METRICS_TOKEN
    ? existingApp.METRICS_TOKEN
    : randomBytes(32).toString("hex");

const cronSecret =
  existingApp.CRON_SECRET || rootEnv.CRON_SECRET || randomBytes(24).toString("hex");

const s3Configured = Boolean(
  (rootEnv.S3_ACCESS_KEY_ID && rootEnv.S3_SECRET_ACCESS_KEY && rootEnv.S3_BUCKET) ||
    (existingApp.S3_ACCESS_KEY_ID && existingApp.S3_SECRET_ACCESS_KEY && existingApp.S3_BUCKET),
);

// Root env first (provider keys), then explicit production topology.
const app = {
  ...existingApp,
  ...rootEnv,
  NODE_ENV: "production",
  LOG_LEVEL: rootEnv.LOG_LEVEL ?? "info",
  DATABASE_URL: `postgresql://tartly:${postgresPassword}@postgres:5432/tartly`,
  DB_POOL_MAX: "8",
  BETTER_AUTH_URL: origin,
  NEXT_PUBLIC_BETTER_AUTH_URL: origin,
  UPSTASH_REDIS_REST_URL: "http://redis-http:80",
  UPSTASH_REDIS_REST_TOKEN: redisToken,
  // Prefer R2/S3 when credentials exist; otherwise keep using Vercel Blob.
  ASSET_STORAGE_DRIVER: s3Configured ? "s3" : "vercel-blob",
  ASSET_BLOB_ACCESS: rootEnv.ASSET_BLOB_ACCESS ?? "private",
  CRON_SECRET: cronSecret,
  METRICS_TOKEN: metricsToken,
  CSP_MODE: rootEnv.CSP_MODE ?? "report",
  API_CONTRACT_VALIDATION: rootEnv.API_CONTRACT_VALIDATION ?? "enforce",
  TZ: "UTC",
};

if (app.ASSET_STORAGE_DRIVER !== "s3") delete app.BLOB_READ_WRITE_TOKEN;

const required = [
  "DATABASE_URL",
  "BETTER_AUTH_SECRET",
  "BETTER_AUTH_URL",
  "NEXT_PUBLIC_BETTER_AUTH_URL",
  "GOOGLE_CLIENT_ID",
  "GOOGLE_CLIENT_SECRET",
  "UPSTASH_REDIS_REST_URL",
  "UPSTASH_REDIS_REST_TOKEN",
];
const missing = required.filter((k) => !app[k]);
if (missing.length) {
  console.error(`\n✖ Missing required values in ${resolve(repoRoot, ".env")}: ${missing.join(", ")}\n`);
  process.exit(1);
}
if (!app.BETTER_AUTH_SECRET || app.BETTER_AUTH_SECRET.length < 32) {
  console.warn("⚠ BETTER_AUTH_SECRET is short; use `openssl rand -base64 32`.");
}

const header = `# Generated by deploy/scripts/render-env.mjs — do not commit.
# Source of truth: repo-root .env (provider keys) + deploy/.env (infra).
# Re-run to sync; generated secrets are preserved.
`;

const body = Object.entries(app)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => serialize(k, v))
  .join("\n");

writeFileSync(resolve(deployDir, "app.env"), `${header}\n${body}\n`, { mode: 0o600 });
chmodSync(resolve(deployDir, "app.env"), 0o600);

const nextInfra = {
  ...infra,
  PUBLIC_URL: origin,
  TARTLY_DOMAIN: domain,
  ACME_EMAIL: infra.ACME_EMAIL ?? `admin@${domain}`,
  POSTGRES_PASSWORD: postgresPassword,
  REDIS_REST_TOKEN: redisToken,
  TAG: infra.TAG ?? "latest",
  NEXT_PUBLIC_IMAGEKIT_URL_ENDPOINT: app.NEXT_PUBLIC_IMAGEKIT_URL_ENDPOINT ?? "",
  NEXT_PUBLIC_CAL_BOOKING_LINK: app.NEXT_PUBLIC_CAL_BOOKING_LINK ?? "",
  NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION: app.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION ?? "",
  NEXT_PUBLIC_MICROSOFT_CONNECT_ENABLED: app.NEXT_PUBLIC_MICROSOFT_CONNECT_ENABLED ?? "false",
};

const infraBody = Object.entries(nextInfra)
  .map(([k, v]) => serialize(k, v))
  .join("\n");
writeFileSync(
  resolve(deployDir, ".env"),
  `# Generated by deploy/scripts/render-env.mjs — do not commit.\n${infraBody}\n`,
  { mode: 0o600 },
);
chmodSync(resolve(deployDir, ".env"), 0o600);

const optionalMissing = [
  "MICROSOFT_CLIENT_ID",
  "DODO_PAYMENTS_API_KEY",
  "SEARCH_API_KEY",
  "GOOGLE_PUBSUB_TOPIC",
  "S3_ACCESS_KEY_ID",
  "NEXT_PUBLIC_IMAGEKIT_URL_ENDPOINT",
].filter((k) => !app[k]);

console.log(`✓ deploy/app.env        (${Object.keys(app).length} vars, mode 600)`);
console.log(`✓ deploy/.env           (infra values, mode 600)`);
console.log(`  origin                ${origin}`);
console.log(`  asset driver          ${app.ASSET_STORAGE_DRIVER}`);
if (optionalMissing.length) {
  console.log(`  optional, unset       ${optionalMissing.join(", ")}`);
}
